//! Демонстрация работы tree-sitter парсера BSL

use bsl_gradual_types::parsing::bsl::ParserFactory;

fn main() -> anyhow::Result<()> {
    println!("=== Демонстрация tree-sitter парсера BSL ===\n");

    // Тестовый BSL код с различными конструкциями
    let code = r#"
// Комментарий - теперь поддерживается!
Процедура ОбработатьДанные(МассивДанных) Экспорт
    // Ещё один комментарий внутри процедуры
    Перем Результат;
    Результат = Новый Массив;
    
    // Цикл Для Каждого
    Для Каждого Элемент Из МассивДанных Цикл
        Если ТипЗнч(Элемент) = Тип("Число") Тогда
            Результат.Добавить(Элемент * 2);
        ИначеЕсли ТипЗнч(Элемент) = Тип("Строка") Тогда
            Результат.Добавить(СтрДлина(Элемент));
        Иначе
            Продолжить;
        КонецЕсли;
    КонецЦикла;
    
    // Цикл Для
    Для Индекс = 0 По Результат.Количество() - 1 Цикл
        Сообщить(СтрШаблон("Элемент %1: %2", Индекс, Результат[Индекс]));
    КонецЦикла;
    
    Возврат Результат;
КонецПроцедуры

Функция Факториал(Н)
    Если Н <= 1 Тогда
        Возврат 1;
    КонецЕсли;
    
    Возврат Н * Факториал(Н - 1);
КонецФункции
"#;

    // Создаём tree-sitter парсер
    let mut parser = ParserFactory::create();
    println!("Используется парсер: {}\n", parser.name());

    // Парсим код
    match parser.parse(code) {
        Ok(program) => {
            println!("✅ Парсинг успешен!");
            println!(
                "Найдено {} операторов верхнего уровня\n",
                program.statements.len()
            );

            // Выводим информацию о найденных элементах
            for (i, stmt) in program.statements.iter().enumerate() {
                use bsl_gradual_types::parsing::bsl::Statement;
                match stmt {
                    Statement::ProcedureDecl {
                        name,
                        params,
                        body,
                        export,
                    } => {
                        println!("{}. Процедура '{}'", i + 1, name);
                        println!("   - Параметров: {}", params.len());
                        println!("   - Операторов в теле: {}", body.len());
                        println!("   - Экспортная: {}", if *export { "Да" } else { "Нет" });
                    }
                    Statement::FunctionDecl {
                        name, params, body, ..
                    } => {
                        println!("{}. Функция '{}'", i + 1, name);
                        println!("   - Параметров: {}", params.len());
                        println!("   - Операторов в теле: {}", body.len());
                    }
                    _ => {
                        println!("{}. Другой оператор", i + 1);
                    }
                }
            }

            println!("\n🎉 Tree-sitter парсер успешно обрабатывает:");
            println!("   ✓ Комментарии");
            println!("   ✓ Процедуры и функции");
            println!("   ✓ Циклы (Для, Для Каждого, Пока)");
            println!("   ✓ Условные операторы");
            println!("   ✓ Вложенные конструкции");
        }
        Err(e) => {
            println!("❌ Ошибка парсинга: {:?}", e);
        }
    }

    Ok(())
}
